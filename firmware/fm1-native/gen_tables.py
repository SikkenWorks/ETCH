#!/usr/bin/env python3
"""Offline fixed wave mip banks and pitch increments, at FM1 24MHz/544 output rate."""
from pathlib import Path
import math
p=Path(__file__).resolve().parent/'native_tables.h'
rows=[]
for w in range(3):
 levels=[]
 for h in [64,32,16,8,2,1]:
  table=[]
  for i in range(512):
   phase=2*math.pi*i/512
   if w==0: value=math.sin(phase)
   elif w==1:value=sum(math.sin(k*phase)/k for k in range(1,h+1))
   else:value=sum((-1)**((k-1)//2)*math.sin(k*phase)/(k*k) for k in range(1,h+1,2))
   table.append(value)
  peak=max(abs(v) for v in table)
  levels.append('{'+','.join(str(round(v/peak*29000)) for v in table)+'}')
 rows.append('{'+',\n'.join(levels)+'}')
incs=[round(440*2**((n-69)/12)/(24000000/544)*2**32) for n in range(128)]
p.write_text('/* Generated by gen_tables.py; no runtime float or table rebuild. */\n#pragma once\n#include <stdint.h>\nstatic const int16_t etch_tables[3][6][512]={'+',\n'.join(rows)+'};\nstatic const uint32_t etch_note_inc[128]={'+','.join(str(v)+'u' for v in incs)+'};\n')
