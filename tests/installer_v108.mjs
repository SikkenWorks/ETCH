import fs from 'node:fs';
import vm from 'node:vm';
import { strict as assert } from 'node:assert';
import {webcrypto} from 'node:crypto';
const html=fs.readFileSync(new URL('../../ETCH-WebInstaller-V1.08.html',import.meta.url),'utf8');
const pkg=fs.readFileSync(new URL('../../ETCH-V1.08-V089-BOOT-COMPAT-EXPERIMENTAL.fwsc.lab',import.meta.url));
const m=html.match(/<script id="firmware-embedded" type="application\/octet-stream">([\s\S]*?)<\/script>/);
assert(m);
assert.equal(Buffer.compare(Buffer.from(m[1].replace(/\s/g,''),'base64'),pkg),0);
const js=html.match(/<script>\/\* SPDX-([\s\S]*?)<\/script>/);
assert(js);
const sandbox={module:{exports:{}},crypto:webcrypto,Uint8Array,Array,Promise,Math,Date,setTimeout,clearTimeout};
sandbox.globalThis=sandbox;
vm.runInNewContext(js[0].slice('<script>'.length,-'</script>'.length),sandbox,{timeout:5000});
const api=sandbox.module.exports;
assert.equal(api.C.ID_ET,'FM-1_1008');
assert.equal(api.C.KNOWN_HEAD_HASH,'d9f43191777656de01c7bed4f9e9ba2e34e94832c5d2ed02c3fc7ab7a6d9bd67');
assert(html.includes("'FM-1_1007'].includes(device.id.text)"),'should accept upgrade from V1.07');
const image=await api.verifyPackage(new Uint8Array(pkg),'etch');
assert.equal(image.product,'FM-1_1008');
assert(image.image.length>=0x93000);
assert(html.includes('V1.08'));
console.log('PASS V1.08 webinstaller embedded firmware, header, version, V1.07 upgrade and CRC/hash verification');
