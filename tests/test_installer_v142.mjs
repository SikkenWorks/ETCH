import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
const root=path.resolve(import.meta.dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'RELEASE-MANIFEST.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'WebInstaller.html'),'utf8');
const fwsc=fs.readFileSync(path.join(root,manifest.firmware_file));
const match=html.match(/<script id="firmware-embedded" type="application\/octet-stream">\s*([\s\S]*?)\s*<\/script>/);
assert.ok(match,'missing firmware in installer');
const embedded=Buffer.from(match[1].replace(/\s/g,''),'base64');
assert.deepEqual(embedded,fwsc,'installer firmware must equal release firmware');
assert.equal(manifest.firmware_identity,'FM-1_1042');
assert.equal(crypto.createHash('sha256').update(fwsc).digest('hex'),manifest.fwsc_sha256);
const script=html.match(/<script>\s*(\/\* SPDX-License-Identifier:[\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'missing OTA JavaScript verifier');
const context={crypto:crypto.webcrypto,Uint8Array,ArrayBuffer,TextEncoder,console,module:{exports:{}},setTimeout,clearTimeout};context.globalThis=context;
vm.runInNewContext(script,context,{filename:'ETCH V1.42 OTA verifier'});
const verify=context.module.exports.verifyPackage;
assert.equal(typeof verify,'function');
const verified=await verify(new Uint8Array(fwsc),'etch');
assert.equal(verified.product,manifest.firmware_identity);
assert.equal(verified.hash,manifest.fwsc_sha256);
const damaged=new Uint8Array(fwsc);damaged[41000]^=1;
await assert.rejects(verify(damaged,'etch'),/hash does not match/);
assert.equal(context.module.exports.isSupportedEtchIdentity('FM-1_1041'),true);
assert.equal(context.module.exports.isSupportedEtchIdentity('FM-1_1042'),true);
assert.equal(context.module.exports.isSupportedEtchIdentity('FM-1_777'),false);
console.log('PASS V1.42 installer, CRC/SHA, compatible identity, byte-perfect firmware and corruption rejection');
