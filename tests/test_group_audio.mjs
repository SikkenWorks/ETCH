import assert from 'node:assert/strict';
import {primitive,compileWave,defaults} from '../sim/dsp.mjs';
globalThis.sampleRate=44100;
globalThis.AudioWorkletProcessor=class{constructor(){this.port={onmessage:null,postMessage(){}};}};
globalThis.registerProcessor=(id,ctor)=>{globalThis.EtchGroupTest=ctor;};
await import('../sim/worklet.mjs');
const w=new globalThis.EtchGroupTest();
const sine=compileWave(primitive('SINE'));
const bank=[sine,sine,sine];
function message(d){w.port.onmessage({data:d});}
message({type:'bank',bank});
message({type:'params',params:{...defaults}});
message({type:'groupConfig',groups:[{bank,params:{...defaults,morph:0,attack:.001}},{bank,params:{...defaults,morph:1,attack:.001}}]});
assert.deepEqual(w.groupEnabled,[true,true]);
message({type:'groupOn',group:1,note:48,velocity:.9,channel:0});
message({type:'groupOn',group:2,note:72,velocity:.9,channel:1});
assert.equal(w.synth.activeVoices(),0);
assert.equal(w.groups[0].activeVoices(),1);
assert.equal(w.groups[1].activeVoices(),1);
const output=new Float32Array(128);
for(let j=0;j<3;j++)w.process([] ,[[output]]);
assert.ok(output.every(Number.isFinite));
message({type:'groupOff',group:1,note:48});
assert.ok(w.groups[0].voices.some(v=>v.stage===4));
assert.ok(w.groups[1].voices.some(v=>v.note===72&&v.stage!==4));
message({type:'panic'});
assert.equal(w.groups[0].activeVoices(),0);
assert.equal(w.groups[1].activeVoices(),0);
console.log('Independent Group presets / audio routing / note release / panic passed');
