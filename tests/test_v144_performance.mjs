import assert from 'node:assert/strict';
import {emptyPerformanceMacros,validatePerformanceMacros,readMacro,writeMacro,captureScene,recallScene} from '../sim/performance-mode.mjs';
const p={morph:.5,depth:.25,cutoff:9000,drive:.6,reverb:.1};
let m=emptyPerformanceMacros();
assert.deepEqual(m.targets,[0,1,2,3]);
assert.equal(recallScene(m,p,0),null);
m=captureScene(m,p,0);
assert.deepEqual(m.scenes[0],[50,25,50,60]);
m.targets=[4,1,2,3];m=captureScene(m,{...p,reverb:.8},1);
const b=recallScene(m,{...p,reverb:0},1);
assert.equal(readMacro(b,4),80);
assert.equal(b.depth,.25);
const old=validatePerformanceMacros(undefined);
assert.deepEqual(old,emptyPerformanceMacros());
assert.throws(()=>validatePerformanceMacros({targets:[8,1,2,3],scenes:[null,null]}));
assert.throws(()=>validatePerformanceMacros({targets:[0,1,2,3],scenes:[[101,2,3,4],null]}));
assert.equal(writeMacro(p,2,0).cutoff,20);
assert.equal(writeMacro(p,2,100).cutoff,18000);
console.log('PASS V1.44 browser performance macros, scenes, defaults, validation');
